#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
build_data.py
=============
Reads `merge data.xlsx` (Sheet2) and writes `webapp/data.js`, a single
JavaScript file that assigns `window.EMP_RAW = [ ...raw employee rows... ]`.

Only the RAW, column-mapped rows are emitted. All derived fields (reporting
lines, spans, depth) and every anomaly/statistic are computed in the browser by
`webapp/dataloader.js`. This guarantees the bundled data and any file the user
loads in-browser go through the exact same analysis code — issues are always
discovered dynamically from whatever data is present.

Emitting a .js file (not .json) lets the app run by double-clicking index.html
with no local server. Run:  python build_data.py  (or refresh_data.bat)
"""

import json
import os
import sys
from collections import defaultdict, Counter
from datetime import datetime

import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "merge data.xlsx")
OUT_DIR = os.path.join(HERE, "webapp")
OUT = os.path.join(OUT_DIR, "data.js")
SHEET = "Sheet2"

# Column index (0-based) -> clean field name. Columns not listed are ignored.
# dataloader.js maps the same fields by header-text (with this order as fallback),
# so a re-ordered export still loads correctly in the browser.
COLMAP = {
    0: "branchCode", 1: "code", 2: "nameEn", 3: "hireDate", 4: "birthDate",
    5: "idNumber", 6: "site", 7: "division", 8: "department", 9: "section",
    10: "costCenter", 11: "costCenterCode", 12: "position", 13: "nationality",
    14: "gender", 15: "managerCode",
}
GENDER = {"1": "Male", "2": "Female", "M": "Male", "F": "Female"}


def norm(v):
    if v is None:
        return ""
    if isinstance(v, datetime):
        return v.strftime("%d/%m/%Y")
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    s = str(v).strip()
    return "" if s.upper() == "NA" else s


def load_rows():
    if not os.path.exists(SRC):
        sys.exit("ERROR: source file not found: %s" % SRC)
    wb = openpyxl.load_workbook(SRC, read_only=True, data_only=True)
    if SHEET not in wb.sheetnames:
        sys.exit("ERROR: sheet '%s' not found. Sheets: %s" % (SHEET, wb.sheetnames))
    ws = wb[SHEET]
    employees = []
    for r in ws.iter_rows(min_row=2, values_only=True):
        code = norm(r[1]) if len(r) > 1 else ""
        if not code:
            continue
        emp = {}
        for idx, field in COLMAP.items():
            val = norm(r[idx]) if idx < len(r) else ""
            if field == "gender":
                val = GENDER.get(val.upper(), val)
            elif field == "managerCode" and val.upper().replace(" ", "_") == "NO_MANAGER":
                val = ""
            emp[field] = val
        employees.append(emp)
    wb.close()
    return employees


def summarize(employees):
    """Compute the same numbers the web app shows — for operator confidence only."""
    by = {e["code"]: e for e in employees}
    reports = defaultdict(list)
    for e in employees:
        m = e["managerCode"]
        if m and m in by:
            reports[m].append(e["code"])
    orphans = [e for e in employees if not e["managerCode"]]
    dangling = [e for e in employees if e["managerCode"] and e["managerCode"] not in by]
    cross = 0
    for e in employees:
        m = by.get(e["managerCode"])
        if not m:
            continue
        if (e["department"] and m["department"] and e["department"] != m["department"]) \
           or (e["division"] and m["division"] and e["division"] != m["division"]) \
           or (e["site"] and m["site"] and e["site"] != m["site"]):
            cross += 1
    spans = [len(v) for v in reports.values()]
    dup_ids = sum(v - 1 for v in Counter(e["idNumber"] for e in employees if e["idNumber"]).values() if v > 1)
    print("=" * 56)
    print("  Employee Hierarchy - data build complete")
    print("=" * 56)
    print("  Employees          : %d" % len(employees))
    print("  Managers           : %d  (avg span %.1f, max %d)"
          % (len(reports), (sum(spans) / len(spans) if spans else 0), max(spans) if spans else 0))
    print("  Orphans (no mgr)   : %d" % len(orphans))
    print("  Mgr code not found : %d" % len(dangling))
    print("  Cross-line reports : %d" % cross)
    print("  Duplicate-ID rows  : %d" % dup_ids)
    print("-" * 56)


def build():
    employees = load_rows()
    summarize(employees)
    payload = {
        "generatedAt": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "sourceFile": os.path.basename(SRC),
        "employees": employees,
    }
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by build_data.py - do not edit by hand.\n")
        f.write("// Regenerate by double-clicking refresh_data.bat.\n")
        f.write("window.EMP_RAW = ")
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print("  Written: %s" % OUT)
    print("  Open webapp/index.html in your browser.")
    print("  (Tip: you can also load a new .xlsx directly in the app - no rebuild.)")
    print("=" * 56)


if __name__ == "__main__":
    build()
